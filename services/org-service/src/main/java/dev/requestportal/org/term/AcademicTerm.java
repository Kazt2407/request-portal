package dev.requestportal.org.term;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.PrePersist;
import jakarta.persistence.Table;
import java.time.Instant;
import java.time.LocalDate;

@Entity
@Table(name = "academic_term")
public class AcademicTerm {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(name = "school_year", nullable = false, updatable = false, length = 9)
    private String schoolYear;

    @Column(name = "term_number", nullable = false, updatable = false)
    private short termNumber;

    /** Generated by the database from school year and term number. */
    @Column(insertable = false, updatable = false, length = 16)
    private String code;

    @Column(nullable = false, length = 100)
    private String name;

    @Column(name = "starts_on", nullable = false)
    private LocalDate startsOn;

    @Column(name = "ends_on", nullable = false)
    private LocalDate endsOn;

    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    protected AcademicTerm() {
    }

    public AcademicTerm(String schoolYear, short termNumber, String name, LocalDate startsOn, LocalDate endsOn) {
        this.schoolYear = schoolYear;
        this.termNumber = termNumber;
        this.code = schoolYear + "-" + termNumber;
        this.name = name;
        this.startsOn = startsOn;
        this.endsOn = endsOn;
    }

    @PrePersist
    void onCreate() {
        createdAt = Instant.now();
    }

    public Long getId() {
        return id;
    }

    public String getSchoolYear() {
        return schoolYear;
    }

    public short getTermNumber() {
        return termNumber;
    }

    public String getCode() {
        return code;
    }

    public String getName() {
        return name;
    }

    public LocalDate getStartsOn() {
        return startsOn;
    }

    public LocalDate getEndsOn() {
        return endsOn;
    }
}
